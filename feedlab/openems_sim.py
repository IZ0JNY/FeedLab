"""Full-wave simulation with openEMS (FDTD, free, https://openems.de).

`make_script(geo, ...)` writes a self-contained Python script (modelled on the official openEMS
'Conical_Horn_Antenna' tutorial: AddRotPoly + AddCircWaveGuidePort TE11 + NF2FF box) that
computes S11 over the band and the far field (E/H/45° cuts with phase) and stores everything in
`results.json`, which the GUI can load (`load_results`).

`openems_available()` tells whether openEMS' Python bindings are importable on this machine;
`run(...)` launches the script in a subprocess.
"""
from __future__ import annotations

import json
import math
import subprocess
import sys
import textwrap
from pathlib import Path

import numpy as np

from .geometry import FeedGeometry
from .patterns import Pattern


def openems_available() -> bool:
    try:
        import openEMS  # noqa: F401
        import CSXCAD  # noqa: F401
        return True
    except Exception:
        return False


def make_script(geo: FeedGeometry, out_dir: str | Path, f_lo: float | None = None, f_hi: float | None = None,
                cells_per_lambda: int = 20, port_mode: str = "TE11", nr_ts: int = 60000) -> Path:
    if not hasattr(geo, "polygons"):
        raise ValueError("full-wave script currently supports rotationally symmetric feeds only")
    out_dir = Path(out_dir); out_dir.mkdir(parents=True, exist_ok=True)
    f0 = geo.f_ghz
    f_lo = f_lo or 0.9 * f0
    f_hi = f_hi or 1.1 * f0
    polys = [[[float(r) for r, _ in p], [float(z) for _, z in p]] for p in geo.polygons]
    meta = {"kind": geo.kind, "f0_ghz": f0, "params": geo.params}
    script = f'''\
# Auto-generated by FeedLab (mwFeedDesign) — openEMS full-wave simulation of a {geo.kind} feed
# Run:  python {('sim_' + geo.kind + '.py')}      (needs openEMS >= 0.0.36 with Python bindings)
import os, json, numpy as np
from CSXCAD import ContinuousStructure
from openEMS import openEMS
from openEMS.physical_constants import C0

HERE = os.path.dirname(os.path.abspath(__file__))
Sim_Path = os.path.join(HERE, 'sim_data')
unit = 1e-3                                   # mm
f0, f_lo, f_hi = {f0}e9, {f_lo}e9, {f_hi}e9
CELLS_PER_LAMBDA = {cells_per_lambda}         # 20 = quick, 40 = good, 60 = OE2IGL quality
POLYS = {json.dumps(polys)}                   # metal cross-sections (r, z) in mm, revolved about z
R_IN  = {geo.r_input:.6f}                     # input guide radius (mm)
Z_AP  = {geo.z_aperture:.6f}                  # aperture plane (mm)
R_MAX = {geo.outer_radius:.6f}
META  = {json.dumps(meta)}

lam_min = C0 / f_hi / unit
res = lam_min / CELLS_PER_LAMBDA
lam0 = C0 / f0 / unit
FDTD = openEMS(NrTS={nr_ts}, EndCriteria=1e-4)
FDTD.SetGaussExcite(0.5 * (f_lo + f_hi), 0.5 * (f_hi - f_lo))
FDTD.SetBoundaryCond(['PML_8'] * 6)
CSX = ContinuousStructure(); FDTD.SetCSX(CSX)
mesh = CSX.GetGrid(); mesh.SetDeltaUnit(unit)

pad = lam0 / 2 + 10 * res
z_back = -max(lam0, 3 * R_IN)                 # input guide runs into the back PML
xy = sorted(set([-R_MAX - pad, R_MAX + pad, 0.0, -R_IN, R_IN]
                + [s * float(r) for p in POLYS for r in p[0] for s in (1, -1)]))
mesh.SetLines('x', xy); mesh.SmoothMeshLines('x', res, ratio=1.4)
mesh.SetLines('y', mesh.GetLines('x'))
zl = sorted(set([z_back, Z_AP + pad] + [float(z) for p in POLYS for z in p[1]]))
mesh.SetLines('z', zl); mesh.SmoothMeshLines('z', res, ratio=1.4)
z_lines = mesh.GetLines('z'); x_lines = mesh.GetLines('x'); y_lines = mesh.GetLines('y')

metal = CSX.AddMetal('feed')
# extend the input guide backwards into the PML (matched input)
metal.AddRotPoly(points=np.array([[R_IN + 0.5, R_IN + 0.5, R_IN, R_IN], [z_back, 0.0, 0.0, z_back]]),
                 norm_dir='x', elevation=0, rot_axis='z', angle=[0, 2 * np.pi], priority=10)
for p in POLYS:
    metal.AddRotPoly(points=np.array(p), norm_dir='x', elevation=0, rot_axis='z',
                     angle=[0, 2 * np.pi], priority=10)

start = [-R_IN, -R_IN, z_lines[10]]
stop  = [ R_IN,  R_IN, z_lines[10] + 0.25 * lam0]
port = FDTD.AddCircWaveGuidePort(0, start, stop, 'z', R_IN * unit, '{port_mode}', 0, 1)

nf_start = [x_lines[8], y_lines[8], z_lines[8]]
nf_stop  = [x_lines[-9], y_lines[-9], z_lines[-9]]
nf2ff = FDTD.CreateNF2FFBox('nf2ff', nf_start, nf_stop, directions=[1, 1, 1, 1, 0, 1])

if __name__ == '__main__':
    FDTD.Run(Sim_Path, cleanup=True)
    freq = np.linspace(f_lo, f_hi, 101)
    port.CalcPort(Sim_Path, freq)
    s11 = port.uf_ref / port.uf_inc
    theta = np.arange(0.0, 180.5, 1.0)
    phis = np.array([0.0, 45.0, 90.0])
    r = nf2ff.CalcNF2FF(Sim_Path, f0, theta, phis, center=[0, 0, Z_AP * unit])
    Et, Ep = r.E_theta[0], r.E_phi[0]          # shape (theta, phi), complex
    out = dict(meta=META, freq_ghz=(freq / 1e9).tolist(),
               s11_re=np.real(s11).tolist(), s11_im=np.imag(s11).tolist(),
               theta=theta.tolist(), phis=phis.tolist(),
               Et_re=np.real(Et).tolist(), Et_im=np.imag(Et).tolist(),
               Ep_re=np.real(Ep).tolist(), Ep_im=np.imag(Ep).tolist(),
               Dmax_dbi=float(10 * np.log10(r.Dmax[0])), Prad=float(r.Prad[0]),
               phase_ref='aperture plane z = Z_AP', cells_per_lambda=CELLS_PER_LAMBDA)
    with open(os.path.join(HERE, 'results.json'), 'w') as fh:
        json.dump(out, fh)
    print('S11 @ f0 = %.1f dB, Dmax = %.2f dBi' % (20 * np.log10(abs(np.interp(f0, freq, s11))), out['Dmax_dbi']))
'''
    path = out_dir / f"sim_{geo.kind}.py"
    path.write_text(textwrap.dedent(script))
    return path


def run(script: Path, log: Path | None = None) -> subprocess.Popen:
    log = log or script.with_suffix(".log")
    fh = open(log, "w")
    return subprocess.Popen([sys.executable, str(script)], cwd=str(script.parent), stdout=fh, stderr=subprocess.STDOUT)


def load_results(path: str | Path) -> dict:
    d = json.loads(Path(path).read_text())
    theta = np.array(d["theta"])
    Et = np.array(d["Et_re"]) + 1j * np.array(d["Et_im"])
    Ep = np.array(d["Ep_re"]) + 1j * np.array(d["Ep_im"])
    # BOR1 co-pol: E-plane (phi=0) -> E_theta, H-plane (phi=90) -> -E_phi
    pat = Pattern(theta, Et[:, 0], -Ep[:, 2], name=f"openEMS {d['meta']['kind']}")
    xpol45 = 20 * np.log10(np.abs((Et[:, 1] - (-Ep[:, 1]))) / 2 + 1e-15)  # rough Ludwig-3 xpol at 45°
    s11 = np.array(d["s11_re"]) + 1j * np.array(d["s11_im"])
    return {"pattern": pat, "freq_ghz": np.array(d["freq_ghz"]), "s11": s11, "Dmax_dbi": d["Dmax_dbi"],
            "xpol45_db": xpol45, "raw": d}
